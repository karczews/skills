#!/usr/bin/env python3
"""Build two previews of every docs/diagramize/*.mmd, drawn the way diagramize
draws them:

- preview.html: HTML pages, with references/mermaid-light.json on a light page
  and references/mermaid-dark.json on a dark page, plus the Markdown form on a
  dark page.
- preview.md: Markdown files, with mermaid-light.json in each block.

Each source is parse-checked with mermaid-cli first when npx is available. The
pre-commit hook in .githooks/ runs this script when a config or a source changes."""

import html
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFS = ROOT / "plugins/explain/skills/diagramize/references"
LIGHT = REFS / "mermaid-light.json"
DARK = REFS / "mermaid-dark.json"
OUT = ROOT / "docs/diagramize"
ORDER = ["flowchart", "sequence", "state", "class", "er"]
MERMAID = "12.2.0"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
REFS_LINK = "../../plugins/explain/skills/diagramize/references"
GENERATED = ("Generated by scripts/render-diagramize-preview.py. Edit docs/diagramize/*.mmd "
             "or plugins/explain/skills/diagramize/references/mermaid-*.json, not this file.")
# Each figure in preview.html: (CSS class, caption, config name).
FIGURES = [
    ("light", "HTML or Markdown, light page", "light"),
    ("dark", "HTML, dark page", "dark"),
    ("dark", "Markdown, dark page", "light"),
]


def yaml(value, indent=0):
    """Write a JSON config as YAML for a Mermaid frontmatter block."""
    lines = []
    for key, item in value.items():
        pad = "  " * indent
        if isinstance(item, dict):
            lines.append(f"{pad}{key}:")
            lines.extend(yaml(item, indent + 1))
        else:
            lines.append(f"{pad}{key}: {json.dumps(item)}")
    return lines


def check(sources):
    if not shutil.which("npx"):
        print("npx not found, skipping the parse check", file=sys.stderr)
        return
    env = dict(os.environ)
    if "PUPPETEER_EXECUTABLE_PATH" not in env and os.access(CHROME, os.X_OK):
        env["PUPPETEER_EXECUTABLE_PATH"] = CHROME
    with tempfile.TemporaryDirectory() as tmp:
        for config in (LIGHT, DARK):
            for src in sources:
                result = subprocess.run(
                    ["npx", "-y", "--prefer-offline", f"@mermaid-js/mermaid-cli@{MERMAID}",
                     "-q", "-i", str(src), "-o", f"{tmp}/{src.stem}.svg", "-c", str(config)],
                    env=env, capture_output=True, text=True,
                )
                if result.returncode != 0:
                    sys.exit(f"{src.name} does not parse with {config.name}:\n{result.stderr.strip()}")


def write_markdown(sources, light):
    frontmatter = "\n".join(["---", "config:", *yaml(light, 1), "---"])
    parts = [
        f"<!-- {GENERATED} -->",
        "",
        "# diagramize preview",
        "",
        "Each Mermaid kind as diagramize writes it in a Markdown file, with the settings from "
        f"[`mermaid-light.json`]({REFS_LINK}/mermaid-light.json). Text sits on light fills, "
        "so the diagrams read on light and dark pages. Each viewer draws them with its own "
        "Mermaid version, so details can differ. [`preview.html`](preview.html) shows the "
        "exact look of diagramize's HTML pages.",
    ]
    for src in sources:
        parts += ["", f"## {src.stem}", "", "```mermaid", frontmatter,
                  src.read_text().rstrip("\n"), "```"]
    (OUT / "preview.md").write_text("\n".join(parts) + "\n")
    print(f"Wrote {OUT / 'preview.md'} with {len(sources)} diagrams")


def write_html(sources, configs):
    sections = []
    for src in sources:
        code = html.escape(src.read_text().rstrip("\n"))
        figures = "\n".join(
            f'      <figure class="{cls}"><figcaption>{caption}</figcaption>'
            f'<pre class="mermaid" data-config="{name}">\n{code}\n      </pre></figure>'
            for cls, caption, name in FIGURES
        )
        sections.append(f"""  <section>
    <h2>{src.stem}</h2>
    <div class="row">
{figures}
    </div>
    <details><summary>Source: {src.name}</summary><pre class="src">{code}</pre></details>
  </section>""")

    page = f"""<!doctype html>
<!-- {GENERATED} -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>diagramize preview</title>
<style>
  body {{ margin: 0 auto; max-width: 1440px; padding: 24px 16px; background: #ffffff;
         color: #1f2937; font: 15px/1.5 system-ui, sans-serif; }}
  h1 {{ font-size: 1.5rem; margin: 0 0 4px; }}
  p.lead {{ margin: 0 0 24px; color: #4b5563; max-width: 72ch; }}
  section {{ border-top: 1px solid #e5e7eb; padding: 16px 0 24px; }}
  h2 {{ font-size: 1.1rem; margin: 0 0 12px; }}
  .row {{ display: grid; grid-template-columns: repeat(3, 1fr); gap: 12px; }}
  @media (max-width: 900px) {{ .row {{ grid-template-columns: 1fr; }} }}
  figure {{ margin: 0; padding: 12px; border-radius: 8px; border: 1px solid #e5e7eb; min-width: 0; }}
  figure.light {{ background: #ffffff; }}
  figure.dark {{ background: #0d1117; border-color: #0d1117; }}
  figcaption {{ font-size: 12px; color: #6b7280; margin-bottom: 8px; }}
  figure.dark figcaption {{ color: #9ca3af; }}
  pre.mermaid {{ margin: 0; text-align: center; overflow-x: auto; }}
  pre.mermaid svg {{ max-width: 100%; height: auto; }}
  details {{ margin-top: 12px; }}
  pre.src {{ background: #f3f4f6; padding: 12px; overflow-x: auto; font-size: 13px; }}
  code {{ background: #f3f4f6; padding: 0 4px; }}
</style>
</head>
<body>
  <h1>diagramize preview</h1>
  <p class="lead">Each Mermaid kind as diagramize draws it. HTML pages use <code>mermaid-light.json</code> on a light page and <code>mermaid-dark.json</code> on a dark page. Markdown files always use <code>mermaid-light.json</code>, because a Markdown block cannot follow the viewer's colour scheme.</p>
{chr(10).join(sections)}
<script src="https://cdn.jsdelivr.net/npm/mermaid@{MERMAID}/dist/mermaid.min.js"></script>
<script>
  const configs = {json.dumps(configs, indent=2)};
  (async () => {{
    let n = 0;
    for (const el of document.querySelectorAll("pre.mermaid")) {{
      mermaid.initialize({{ startOnLoad: false, ...configs[el.dataset.config] }});
      const {{ svg }} = await mermaid.render(`diagram-${{n++}}`, el.textContent);
      el.innerHTML = svg;
    }}
  }})();
</script>
</body>
</html>
"""
    (OUT / "preview.html").write_text(page)
    print(f"Wrote {OUT / 'preview.html'} with {len(sources)} diagrams")


def main():
    found = sorted(p.stem for p in OUT.glob("*.mmd"))
    unknown = [n for n in found if n not in ORDER]
    missing = [n for n in ORDER if n not in found]
    if unknown or missing:
        sys.exit(f"sources and ORDER differ: unknown {unknown}, missing {missing}")
    sources = [OUT / f"{n}.mmd" for n in ORDER]
    check(sources)
    configs = {"light": json.loads(LIGHT.read_text()), "dark": json.loads(DARK.read_text())}
    write_html(sources, configs)
    write_markdown(sources, configs["light"])


if __name__ == "__main__":
    main()
